using System.Collections.Generic;
using AniML.Creatures;
using AniML.World;
using UnityEngine;

namespace AniML.Sandbox
{
    /// <summary>
    /// Spawns a herd of 38-DOF PolyArt Deer driven by <see cref="DeerEcologyBrain"/>
    /// and <see cref="DeerPolicyLocomotionMotor"/> (Isaac Lab D2 / D2b AMP+PPO policy)
    /// across reachable meadow and forest-edge habitat on <see cref="ProceduralWorld"/>.
    /// </summary>
    public sealed class SandboxSpawner : MonoBehaviour
    {
        [SerializeField] private CreatureDefinition definition;
        [SerializeField] private int count = 16;
        [SerializeField] private float spawnRadius = 55f;
        [SerializeField] private bool useNeuralPolicy = true;
        [SerializeField] private string primaryPolicyResource = "Policies/deer_polyart_d2";
        [SerializeField] private string secondaryPolicyResource = "Policies/deer_polyart_d2b";

        private readonly List<CreatureController> _spawned = new();

        public IReadOnlyList<CreatureController> SpawnedCreatures => _spawned;

        public CreatureDefinition Definition
        {
            get => definition;
            set => definition = value;
        }

        private void Start()
        {
            // If deer were already placed in Edit Mode (e.g. via WorldTools),
            // wire and wake them up rather than duplicating the herd.
            var existing = GetComponentsInChildren<CreatureController>();
            if (existing != null && existing.Length > 0)
            {
                _spawned.Clear();
                for (int i = 0; i < existing.Length; i++)
                {
                    WireCreatureComponents(existing[i].gameObject, i);
                    _spawned.Add(existing[i]);
                }
                return;
            }

            SpawnHerd();
        }

        /// <summary>
        /// Clears any previously spawned children and spawns <see cref="count"/> deer
        /// on valid terrestrial habitat patches around <c>transform.position</c>.
        /// </summary>
        public void SpawnHerd(ProceduralWorld world = null, int seed = 1337)
        {
            if (world == null)
                world = FindAnyObjectByType<ProceduralWorld>();
            if (world != null)
                world.EnsureSamplers();

            // Clear existing children
            for (int i = transform.childCount - 1; i >= 0; i--)
            {
                var child = transform.GetChild(i).gameObject;
                if (Application.isPlaying)
                    Destroy(child);
                else
                    DestroyImmediate(child);
            }
            _spawned.Clear();

            // Ensure this spawner sits on prime meadow habitat if a world exists
            if (world != null && world.Settings != null)
            {
                Vector3 anchor = FindBestHerdAnchor(world, transform.position);
                transform.position = anchor;
            }

            var rng = new System.Random(seed);
            for (int i = 0; i < count; i++)
            {
                Vector3 pos = SampleValidSpawnPosition(world, transform.position, spawnRadius, rng, i);
                float yaw = (float)(rng.NextDouble() * 360.0);
                var go = SpawnOne(pos, Quaternion.Euler(0f, yaw, 0f), i, world);
                if (go != null && go.TryGetComponent<CreatureController>(out var ctrl))
                    _spawned.Add(ctrl);
            }
        }

        private GameObject SpawnOne(Vector3 position, Quaternion rotation, int index, ProceduralWorld world)
        {
            GameObject go;
            if (definition != null && definition.Prefab != null)
            {
                go = Instantiate(definition.Prefab, position, rotation, transform);
            }
            else
            {
                // Fallback: procedural articulated 31-bone rig generated by DeerRigDriver
                go = new GameObject();
                go.transform.SetParent(transform, false);
                go.transform.SetPositionAndRotation(position, rotation);
            }

            string species = definition != null && !string.IsNullOrEmpty(definition.SpeciesId)
                ? definition.SpeciesId
                : "deer";
            go.name = $"Creature_{species}_{index:00}";

            var controller = WireCreatureComponents(go, index);

            // Step the policy motor a few frames in place so each deer adopts a natural
            // mid-stride or grazing posture aligned to the terrain slope immediately.
            if (controller.Motor is DeerPolicyLocomotionMotor policyMotor)
            {
                policyMotor.EnsureInitialized();
                var fwd = Vector3.ProjectOnPlane(go.transform.forward, Vector3.up).normalized;
                var warmupIntent = new CreatureIntent
                {
                    MoveDirection = fwd.sqrMagnitude > 1e-4f ? fwd : Vector3.forward,
                    Speed01 = (index % 3 == 0) ? 0f : 0.45f,
                };
                policyMotor.IsBrowsingOrDrinking = (index % 3 == 0);
                int warmupSteps = 8 + (index * 5) % 25;
                for (int s = 0; s < warmupSteps; s++)
                    policyMotor.Tick(go.transform, definition, world, in warmupIntent, DeerPolicyLocomotionMotor.PolicyDt);
            }

            return go;
        }

        private CreatureController WireCreatureComponents(GameObject go, int index)
        {
            var controller = go.GetComponent<CreatureController>();
            if (controller == null)
                controller = go.AddComponent<CreatureController>();

            if (useNeuralPolicy)
            {
                var rig = go.GetComponent<DeerRigDriver>();
                if (rig == null)
                    rig = go.AddComponent<DeerRigDriver>();

                var motor = go.GetComponent<DeerPolicyLocomotionMotor>();
                if (motor == null)
                    motor = go.AddComponent<DeerPolicyLocomotionMotor>();

                // Mix D2 (flagship stable trot) and D2b (antler mass domain-randomized) across the herd
                motor.PolicyResourcePath = (index % 4 == 3 && !string.IsNullOrEmpty(secondaryPolicyResource))
                    ? secondaryPolicyResource
                    : primaryPolicyResource;
                motor.EnsureInitialized();

                var brain = go.GetComponent<DeerEcologyBrain>();
                if (brain == null)
                    brain = go.AddComponent<DeerEcologyBrain>();

                controller.Initialize(definition, brain, motor);
            }
            else
            {
                controller.Initialize(definition, new WanderBrain(), new SimpleSteeringMotor());
            }

            return controller;
        }

        public static Vector3 FindBestHerdAnchor(ProceduralWorld world, Vector3 preferredOrigin)
        {
            if (world == null || world.Settings == null)
                return preferredOrigin;

            // Check if preferredOrigin is already on gentle, dry meadow land
            if (ScoreHabitatPatch(world, preferredOrigin.x, preferredOrigin.z) > 1.15f)
            {
                float y = world.SampleHeight(preferredOrigin.x, preferredOrigin.z);
                return new Vector3(preferredOrigin.x, y, preferredOrigin.z);
            }

            float half = world.Settings.WorldSize * 0.38f;
            const float step = 24f;
            Vector3 bestPos = new Vector3(0f, world.SampleHeight(0f, 0f), 0f);
            float bestScore = float.NegativeInfinity;

            for (float z = -half; z <= half; z += step)
            {
                for (float x = -half; x <= half; x += step)
                {
                    float score = ScoreHabitatPatch(world, x, z);
                    if (score > bestScore)
                    {
                        bestScore = score;
                        bestPos = new Vector3(x, world.SampleHeight(x, z), z);
                    }
                }
            }

            return bestPos;
        }

        private static float ScoreHabitatPatch(ProceduralWorld world, float x, float z)
        {
            float h = world.SampleHeight(x, z);
            if (h < world.Settings.SeaLevel + 10.0f || h > 34f)
                return -10f;

            if (world.StandingWaterDepth(x, z) > 0.01f || world.RiverInfluence01(x, z) > 0.05f)
                return -10f;

            Vector3 n = world.SampleNormal(x, z);
            float slopeDeg = Mathf.Acos(Mathf.Clamp(n.y, -1f, 1f)) * Mathf.Rad2Deg;
            if (slopeDeg > 12f)
                return -5f;

            Biome b = world.SampleBiome(x, z);
            if (b != Biome.Meadow)
                return -4f;

            float forest = world.ForestDensity01(x, z);
            if (forest > 0.15f)
                return -3f;

            float moisture = world.SampleMoisture(x, z);
            float openMeadowScore = (moisture >= 0.15f && moisture <= 0.55f) ? 0.6f : 0f;

            float browse = world.SampleBrowse01(x, z);
            float waterAccess = world.SampleWaterAccess01(x, z);

            return 1.0f + openMeadowScore + browse * 1.3f + waterAccess * 0.4f - forest * 3.0f - slopeDeg * 0.04f;
        }

        private static Vector3 SampleValidSpawnPosition(
            ProceduralWorld world, Vector3 center, float radius, System.Random rng, int index)
        {
            if (world == null || world.Settings == null)
            {
                double a = rng.NextDouble() * Mathf.PI * 2.0;
                double r = System.Math.Sqrt(rng.NextDouble()) * radius;
                return center + new Vector3((float)(System.Math.Cos(a) * r), 0f, (float)(System.Math.Sin(a) * r));
            }

            Vector3 best = center;
            float bestScore = float.NegativeInfinity;

            for (int attempt = 0; attempt < 24; attempt++)
            {
                double angle = (index * 2.399963229728653 + attempt * 0.75) % (Mathf.PI * 2.0);
                double dist = (0.15 + 0.85 * rng.NextDouble()) * radius;
                float x = center.x + (float)(System.Math.Cos(angle) * dist);
                float z = center.z + (float)(System.Math.Sin(angle) * dist);

                float score = ScoreHabitatPatch(world, x, z);
                if (score > bestScore)
                {
                    bestScore = score;
                    best = new Vector3(x, world.SampleHeight(x, z), z);
                    if (score > 1.35f && attempt >= 3)
                        break;
                }
            }

            best.y = world.SampleHeight(best.x, best.z);
            return best;
        }
    }
}
